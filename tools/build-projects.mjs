// Collect research projects plus local-only projects (folders whose project.json has "meta").
const dir = resolve(root, 'projects');
if (!existsSync(dir)) await mkdir(dir);
const folders = (await readdir(dir, { withFileTypes: true })).filter(e => e.isDirectory()).map(e => e.name);
const entries = R.projects.map(p => ({ base: p, slug: projectSlug(p.name), research: true }));
for (const f of folders) if (!entries.some(e => e.slug === f) && existsSync(resolve(dir, f, 'project.json'))) {
  const j = JSON.parse(await readFile(resolve(dir, f, 'project.json'), 'utf8'));
  if (j.meta) entries.push({ base: { url: '', tags: '', ...j.meta }, slug: f, research: false });
}

const outputs = new Map(), scaffolds = [];
const projects = [];
for (const { base, slug, research } of entries) {
  const pubs = research ? linkedPubs(base) : [];
  const jsonPath = resolve(dir, slug, 'project.json');
  let data;
  if (existsSync(jsonPath)) data = JSON.parse(await readFile(jsonPath, 'utf8'));
  else { data = scaffold(slug, base, pubs); scaffolds.push(`projects/${slug}/project.json`); outputs.set(`projects/${slug}/project.json`, JSON.stringify(data, null, 2) + '\n'); }
  const readmePath = resolve(dir, slug, 'README.md');
  const readme = existsSync(readmePath) ? await readFile(readmePath, 'utf8') : '';
  const releases = (data.releases || []).map((r, i) => ({ ...r, iso: isoOf(r.date), label: r.label || labelOf(r.date), order: i }))
    .sort((a, b) => b.iso.localeCompare(a.iso) || a.order - b.order);
  const gallery = (data.gallery || []).map(g => ({ ...g, label: g.date ? (g.label || labelOf(g.date)) : (g.label || '') }));
  const proj = {
    slug, name: base.name, theme: base.theme, description: base.description, status: base.status, url: base.url || '', tags: base.tags || '',
    research, stage: data.stage || stageOf(base.status, pubs, Boolean(base.url)), stages: data.stages || null, team: data.team?.length ? data.team : authorsOf(pubs),
    links: data.links || [], publications: pubs.map(({ bibtex, ...x }) => ({ ...x, bibtex })), releases, gallery, readme,
    updated: releases[0] ? releases[0].label : ''
  };
  projects.push(proj);
  outputs.set(`projects/${slug}/index.html`, page(proj));
}

const index = projects.map(({ publications, readme, releases, gallery, ...p }) => ({
  ...p, releaseCount: releases.length, latest: releases[0] ? { tag: releases[0].tag, title: releases[0].title, label: releases[0].label, iso: releases[0].iso } : null,
  galleryCount: gallery.length, cover: gallery[0] ? gallery[0].src : null, types: [...new Set(releases.map(r => r.type))]
}));
const memories = projects.flatMap(p => p.gallery.map(g => ({ ...g, project: p.slug, projectName: p.name })))
  .sort((a, b) => isoOf(b.date || '0000').localeCompare(isoOf(a.date || '0000')));
outputs.set('assets/projects-data.js', `// GENERATED by tools/build-projects.mjs. Do not edit by hand.\nwindow.PROJECTS = ${JSON.stringify(index, null, 1)};\nwindow.MEMORIES = ${JSON.stringify(memories, null, 1)};\n`);

const changed = [];
for (const [rel, content] of outputs) {
  const t = resolve(root, rel);
  if (!existsSync(t) || (await readFile(t, 'utf8')) !== content) changed.push(rel);
}
if (check) {
  if (changed.length) { console.error(`Projects out of date (${changed.join(', ')}). Run: node tools/build-projects.mjs`); process.exit(1); }
  console.log(`Projects up to date: ${projects.length} projects, ${projects.reduce((n, p) => n + p.releases.length, 0)} releases, ${memories.length} memories.`);
} else {
  for (const rel of changed) { const t = resolve(root, rel); await mkdir(dirname(t), { recursive: true }); await writeFile(t, outputs.get(rel)); }
  console.log(`Projects built: ${projects.length} projects; ${changed.length} file(s) written${scaffolds.length ? `; scaffolded ${scaffolds.length} project.json` : ''}.`);
}
