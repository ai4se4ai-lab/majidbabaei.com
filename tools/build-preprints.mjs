// Builds the public Preprints section from ScholarPress release records.
//   Source (written by the ScholarPress export adapter, not by hand):
//     preprints/<slug>/preprint.json        public release record: metadata, links, venue status, every version
//     preprints/<slug>/v<N>/paper.pdf       immutable published PDF bytes for version N
//   Generates:
//     preprints/index.html                  searchable index of released articles
//     preprints/<slug>/index.html           stable landing page (latest version + history)
//     preprints/<slug>/paper.pdf            latest-PDF alias (copy of the newest numbered PDF)
//     preprints/<slug>/v<N>/index.html      permanent release page
//     preprints/<slug>/v<N>/citation.bib    citation generated from public metadata
//     assets/preprints-data.js              read by the homepage, project pages, and the sitemap
// The check refuses a numbered PDF whose bytes differ from its record, so published versions never change.
// Usage: node tools/build-preprints.mjs [--check]
import { readFile, writeFile, readdir, mkdir, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { headOpen, headAssets, header, footer, maskWords } from './chrome.mjs';

const SITE = 'https://majidbabaei.com';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'preprints');
const check = process.argv.includes('--check');
const MARK = '<!-- generated by tools/build-preprints.mjs from preprints/<slug>/preprint.json (ScholarPress); do not edit -->';
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const sha = b => createHash('sha256').update(b).digest('hex');
const dateLabel = iso => { const [y, m, d] = String(iso).split('-'); return d ? `${MONTHS[m - 1]} ${Number(d)}, ${y}` : m ? `${MONTHS[m - 1]} ${y}` : y; };
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const VENUE_STATUS = { preprint: 'Preprint', 'under-review': 'Under review', 'revision-requested': 'Revision requested', accepted: 'Accepted', published: 'Published' };

// ---------- Site catalog: projects, news stories, publications (for validation and readable link names) ----------
const readText = async rel => existsSync(resolve(root, rel)) ? readFile(resolve(root, rel), 'utf8') : '';
const listDir = async rel => existsSync(resolve(root, rel)) ? readdir(resolve(root, rel)) : [];
const rctx = { window: {} };
vm.runInNewContext(await readText('assets/research-data.js'), rctx);
const R = rctx.window.RESEARCH || { projects: [], published: [], submitted: [] };
const projectSlug = name => name.split(' / ')[0].toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const projectNames = new Map(R.projects.map(p => [projectSlug(p.name), p.name]));
for (const f of await listDir('projects')) {
  const pj = `projects/${f}/project.json`;
  if (!projectNames.has(f) && existsSync(resolve(root, pj))) { const j = JSON.parse(await readText(pj)); if (j.meta?.name) projectNames.set(f, j.meta.name); }
}
const newsTitles = new Map();
for (const f of (await listDir('news/posts')).filter(f => f.endsWith('.md'))) {
  const text = await readText(`news/posts/${f}`);
  const t = text.match(/^title:\s*(.+)$/m);
  newsTitles.set(f.replace(/\.md$/, '').replace(/^\d{4}(-\d{2}){0,2}-/, ''), t ? t[1].trim().replace(/^["']|["']$/g, '') : f);
}
const pubs = new Map([...R.published.map(p => [p.key, { ...p, group: 'published' }]), ...R.submitted.map(p => [p.key, { ...p, group: 'submitted' }])]);
// Homepage anchors a release may link from (agenda themes and the artifact grid).
const AGENDA = { research: 'Research agenda', software: 'Research software & artifacts', publications: 'Publications', students: 'Students' };

// ---------- Records ----------
const problems = [];
const articles = [];
const slugs = existsSync(dir) ? (await readdir(dir, { withFileTypes: true })).filter(e => e.isDirectory()).map(e => e.name).sort() : [];
for (const slug of slugs) {
  const path = resolve(dir, slug, 'preprint.json');
  if (!existsSync(path)) continue;
  const rec = JSON.parse(await readFile(path, 'utf8'));
  const where = `preprints/${slug}/preprint.json`;
  if (rec.slug !== slug || !SLUG.test(slug)) { problems.push(`${where}: slug must match its folder and use lowercase words joined by hyphens`); continue; }
  if (rec.disclosure !== 'public') { problems.push(`${where}: only records with disclosure "public" may be in the site checkout`); continue; }
  if (!Array.isArray(rec.versions) || !rec.versions.length) { problems.push(`${where}: no released versions`); continue; }
  rec.versions.sort((a, b) => a.version - b.version);
  rec.versions.forEach((v, i) => { if (v.version !== i + 1) problems.push(`${where}: versions must be numbered 1..N without gaps`); });
  for (const v of rec.versions) {
    const pdf = resolve(dir, slug, `v${v.version}`, 'paper.pdf');
    if (!existsSync(pdf)) { problems.push(`preprints/${slug}/v${v.version}/paper.pdf is missing`); continue; }
    const bytes = await readFile(pdf);
    if (sha(bytes) !== v.sha256) problems.push(`preprints/${slug}/v${v.version}/paper.pdf does not match its recorded SHA-256 (published PDFs are immutable)`);
    if (!bytes.subarray(0, 5).equals(Buffer.from('%PDF-'))) problems.push(`preprints/${slug}/v${v.version}/paper.pdf is not a PDF`);
    v.bytes = bytes.length;
  }
  const links = rec.links || {};
  for (const id of links.projectIds || []) if (!projectNames.has(id)) problems.push(`${where}: unknown project "${id}"`);
  for (const id of links.newsPostIds || []) if (!newsTitles.has(id)) problems.push(`${where}: unknown news story "${id}"`);
  for (const id of links.agendaIds || []) if (!AGENDA[id]) problems.push(`${where}: unknown homepage anchor "${id}"`);
  if (links.publicationId) {
    const p = pubs.get(links.publicationId);
    if (!p) problems.push(`${where}: unknown publication key "${links.publicationId}"`);
    else if (p.anonymous) problems.push(`${where}: publication "${links.publicationId}" is anonymous for review and cannot be linked`);
  }
  articles.push(rec);
}
const seenIds = new Set();
for (const a of articles) { if (seenIds.has(a.articleId)) problems.push(`duplicate articleId ${a.articleId}`); seenIds.add(a.articleId); }

// ---------- Rendering ----------
const authorsText = list => list.map(a => a.name).join(', ');
const bibAuthors = list => list.map(a => a.name).join(' and ');
const bibValue = v => String(v).replace(/[\\{}%&#_$]/g, c => c === '\\' ? '\\textbackslash{}' : `\\${c}`);
const citeKey = (a, v) => `${(a.versions[0].authors[0]?.name || 'anon').split(/\s+/).pop().toLowerCase().replace(/[^a-z]/g, '')}${v.date.slice(0, 4)}${a.slug.replace(/-/g, '').slice(0, 24)}v${v.version}`;
const bibtex = (a, v) => `@misc{${citeKey(a, v)},
  title = {${bibValue(v.title)}},
  author = {${bibValue(bibAuthors(v.authors))}},
  year = {${v.date.slice(0, 4)}},
  month = {${MONTHS[Number(v.date.slice(5, 7)) - 1].toLowerCase()}},
  howpublished = {Preprint, version ${v.version}},
  note = {Version ${v.version}${v.date ? `, released ${v.date}` : ''}},
  url = {${SITE}/preprints/${a.slug}/v${v.version}/}
}
`;
const highwire = (a, v, pdfURL) => [
  ['citation_title', v.title], ...v.authors.map(x => ['citation_author', x.name]),
  ...v.authors.filter(x => x.affiliation).map(x => ['citation_author_institution', x.affiliation]),
  ['citation_publication_date', v.date.replace(/-/g, '/')], ['citation_online_date', v.date.replace(/-/g, '/')],
  ['citation_pdf_url', pdfURL], ['citation_abstract_html_url', `${SITE}/preprints/${a.slug}/v${v.version}/`],
  ['citation_technical_report_institution', 'Preprint'],
  ...(a.venue?.doi && a.venue.status === 'published' ? [['citation_doi', a.venue.doi]] : [])
].map(([n, c]) => `<meta name="${n}" content="${esc(c)}">`).join('\n');

const ROOT2 = '../../', ROOT3 = '../../../';
const linkList = (a, root) => {
  const L = a.links || {}, out = [];
  if (L.publicationId && pubs.has(L.publicationId)) out.push(`<li><a href="${root}#pub-${esc(L.publicationId)}">Publications entry</a><span>${esc(pubs.get(L.publicationId).group === 'published' ? 'Published & accepted' : 'Under review & ongoing')}</span></li>`);
  for (const id of L.projectIds || []) out.push(`<li><a href="${root}projects/${esc(id)}/">${esc(projectNames.get(id))}</a><span>Project</span></li>`);
  for (const id of L.newsPostIds || []) out.push(`<li><a href="${root}news/${esc(id)}/">${esc(newsTitles.get(id))}</a><span>Newsroom</span></li>`);
  for (const id of L.agendaIds || []) out.push(`<li><a href="${root}#${esc(id)}">${esc(AGENDA[id])}</a><span>Homepage</span></li>`);
  return out.length ? `<section class="pp-card"><h2>On this site</h2><ul class="pp-links">${out.join('')}</ul></section>` : '';
};
const venueBlock = a => {
  const v = a.venue;
  if (!v || v.status === 'preprint') return '';
  const official = v.url || (v.doi ? `https://doi.org/${v.doi}` : '');
  return `<section class="pp-card pp-venue"><h2>${esc(VENUE_STATUS[v.status] || v.status)}${v.name ? ` · ${esc(v.name)}` : ''}</h2>
    ${v.citation ? `<p>${esc(v.citation)}</p>` : ''}
    ${v.date ? `<p class="pp-muted">${v.status === 'published' ? 'Venue publication' : 'Status'} date: ${esc(dateLabel(v.date))}</p>` : ''}
    ${official ? `<p><a class="u-link" href="${esc(official)}" rel="noopener">${v.doi ? `DOI ${esc(v.doi)}` : 'Official version'} ↗</a></p>` : ''}
    <p class="pp-muted">This self-hosted preprint remains available below; cite the official version where it exists.</p></section>`;
};
const history = (a, root, current) => `<section class="pp-card"><h2>Version history</h2><ol class="pp-versions" reversed>${[...a.versions].reverse().map(v =>
  `<li${v.version === current ? ' aria-current="true"' : ''}><a href="${root}v${v.version}/"><strong>v${v.version}</strong> · <time datetime="${v.date}">${esc(dateLabel(v.date))}</time></a>${v.note ? `<p>${esc(v.note)}</p>` : ''}<a class="pp-pdf" href="${root}v${v.version}/paper.pdf">PDF<span class="pp-muted"> · ${Math.max(1, Math.round(v.bytes / 1024))} KB</span></a></li>`).join('')}</ol></section>`;

const shell = ({ title, description, canonical, head = '', root, body }) => `<!doctype html>
${MARK}
<html lang="en">
<head>
${headOpen}
<title>${esc(title)} | Majid Babaei</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${canonical}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Majid Babaei">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${canonical}">
<meta property="og:image" content="${SITE}/assets/img/portrait.jpg">
${head}
${headAssets(root, ['news', 'preprints'])}
</head>
<body class="reader" data-page="preprint" data-root="${root}">
<a class="skip" href="#pp-main">Skip to content</a>
${header(root, '#publications')}
<main id="pp-main" class="pp wrap">
${body}
</main>
${footer(root)}
<script src="${root}assets/cv-request.js"></script>
<i id="page-ready" hidden></i>
</body>
</html>
`.replace(/[ \t]+$/gm, '');

const articleBody = (a, v, { root, here, versionPage }) => {
  const latest = a.versions[a.versions.length - 1];
  const pdf = versionPage ? 'paper.pdf' : `v${latest.version}/paper.pdf`;
  return `<header class="pp-head">
  <nav class="crumbs enter" aria-label="Breadcrumb"><a href="${root}#publications">Publications</a><span aria-hidden="true">/</span><a href="${root}preprints/">Preprints</a>${versionPage ? `<span aria-hidden="true">/</span><a href="../">${esc(a.slug)}</a><span aria-hidden="true">/</span><strong>v${v.version}</strong>` : ''}</nav>
  <p class="pp-kicker">${versionPage ? `Version ${v.version} of ${a.versions.length}${v.version === latest.version ? ' · latest' : ` · <a href="../">see the latest version (v${latest.version})</a>`}` : `Preprint · v${latest.version} · updated ${esc(dateLabel(latest.date))}`}</p>
  <h1>${maskWords(v.title, esc)}</h1>
  <p class="pp-authors">${v.authors.map(x => `<span>${esc(x.name)}${x.affiliation ? `<small>${esc(x.affiliation)}</small>` : ''}</span>`).join('')}</p>
  <div class="pp-actions">
    <a class="pj-btn" href="${pdf}" type="application/pdf">Read the PDF</a>
    <a class="pj-btn ghost" href="${pdf}" download="${esc(a.slug)}-v${v.version}.pdf">Download</a>
    <a class="pj-btn ghost" href="${versionPage ? '' : `v${latest.version}/`}citation.bib" download>Cite (BibTeX)</a>
  </div>
</header>
<div class="pp-grid">
  <article class="pp-main">
    <section class="pp-abstract"><h2>Abstract</h2><p>${esc(v.abstract).replace(/\n{2,}/g, '</p><p>')}</p></section>
    ${v.note && versionPage ? `<section class="pp-card"><h2>Revision note</h2><p>${esc(v.note)}</p></section>` : ''}
    <section class="pp-card"><h2>How to cite</h2>
      <p>${esc(authorsText(v.authors))}. ${esc(v.title)}. Preprint, version ${v.version}, ${esc(dateLabel(v.date))}. <a class="u-link" href="${SITE}/preprints/${a.slug}/v${v.version}/">${SITE}/preprints/${a.slug}/v${v.version}/</a></p>
      <pre class="pp-bib">${esc(bibtex(a, v))}</pre>
      <p class="pp-muted">Share the stable link <a class="u-link" href="${SITE}/preprints/${a.slug}/">${SITE}/preprints/${a.slug}/</a>; cite a numbered version for an exact revision.</p>
    </section>
  </article>
  <aside class="pp-side">
    ${venueBlock(a)}
    ${history(a, here, versionPage ? v.version : null)}
    ${linkList(a, root)}
  </aside>
</div>`;
};

const outputs = new Map(), binaries = new Map();
for (const a of articles) {
  const latest = a.versions[a.versions.length - 1];
  const base = `preprints/${a.slug}`;
  const ld = v => `<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@type': 'ScholarlyArticle', headline: v.title, name: v.title, abstract: v.abstract,
    author: v.authors.map(x => ({ '@type': 'Person', name: x.name, ...(x.affiliation ? { affiliation: x.affiliation } : {}) })), datePublished: v.date, version: String(v.version),
    url: `${SITE}/${base}/v${v.version}/`, encoding: { '@type': 'MediaObject', encodingFormat: 'application/pdf', contentUrl: `${SITE}/${base}/v${v.version}/paper.pdf` },
    ...(a.venue?.doi ? { sameAs: `https://doi.org/${a.venue.doi}` } : {}) }).replace(/</g, '\\u003c')}</script>`;
  outputs.set(`${base}/index.html`, shell({ title: latest.title, description: latest.abstract.slice(0, 280), canonical: `${SITE}/${base}/`, root: ROOT2,
    head: `${highwire(a, latest, `${SITE}/${base}/v${latest.version}/paper.pdf`)}\n${ld(latest)}`, body: articleBody(a, latest, { root: ROOT2, here: '', versionPage: false }) }));
  for (const v of a.versions) {
    outputs.set(`${base}/v${v.version}/index.html`, shell({ title: `${v.title} (v${v.version})`, description: v.abstract.slice(0, 280), canonical: `${SITE}/${base}/v${v.version}/`, root: ROOT3,
      head: `${highwire(a, v, `${SITE}/${base}/v${v.version}/paper.pdf`)}\n${ld(v)}`, body: articleBody(a, v, { root: ROOT3, here: '../', versionPage: true }) }));
    outputs.set(`${base}/v${v.version}/citation.bib`, bibtex(a, v));
  }
  binaries.set(`${base}/paper.pdf`, `${base}/v${latest.version}/paper.pdf`);
}
const sorted = [...articles].sort((x, y) => y.versions.at(-1).date.localeCompare(x.versions.at(-1).date) || x.slug.localeCompare(y.slug));
outputs.set('preprints/index.html', shell({ title: 'Preprints', description: 'Self-hosted preprints with stable links and permanent numbered versions.', canonical: `${SITE}/preprints/`, root: '../',
  body: `<header class="pp-head">
  <nav class="crumbs enter" aria-label="Breadcrumb"><a href="../#publications">Publications</a><span aria-hidden="true">/</span><strong>Preprints</strong></nav>
  <h1>${maskWords('Preprints', esc)}</h1>
  <p class="pp-lede">Manuscripts released here before or alongside formal publication. Each has a stable link to its latest version and a permanent link for every numbered revision. A preprint is not a refereed publication; venue status is shown where confirmed.</p>
  <label class="search pp-search"><span class="visually-hidden">Search preprints</span><input id="pp-q" type="search" placeholder="Search title, author, abstract…" autocomplete="off"></label>
</header>
<ol class="pp-index" id="pp-index">${sorted.length ? sorted.map(a => { const v = a.versions.at(-1); return `<li data-text="${esc(`${v.title} ${authorsText(v.authors)} ${v.abstract}`.toLowerCase())}">
  <p class="pp-muted"><time datetime="${v.date}">${esc(dateLabel(v.date))}</time> · v${v.version}${a.venue && a.venue.status !== 'preprint' ? ` · ${esc(VENUE_STATUS[a.venue.status] || '')}${a.venue.name ? ` · ${esc(a.venue.name)}` : ''}` : ''}</p>
  <h2><a href="${a.slug}/">${esc(v.title)}</a></h2><p>${esc(authorsText(v.authors))}</p>
  <p class="pp-row"><a class="u-link" href="${a.slug}/">Article page</a><a class="u-link" href="${a.slug}/v${v.version}/paper.pdf">PDF</a></p></li>`; }).join('') : '<li class="pp-empty">No preprints have been released yet.</li>'}</ol>
<p class="pp-empty" id="pp-none" hidden>No matching preprints.</p>
<script>(()=>{const q=document.getElementById('pp-q'),items=[...document.querySelectorAll('#pp-index li[data-text]')],none=document.getElementById('pp-none');q&&q.addEventListener('input',()=>{const s=q.value.trim().toLowerCase();let n=0;items.forEach(li=>{const ok=!s||li.dataset.text.includes(s);li.hidden=!ok;n+=ok});none.hidden=n>0||!items.length})})();</script>` }));

const data = articles.map(a => {
  const v = a.versions.at(-1);
  return { articleId: a.articleId, slug: a.slug, title: v.title, authors: v.authors.map(x => x.name), date: v.date, firstDate: a.versions[0].date, version: v.version,
    url: `preprints/${a.slug}/`, pdf: `preprints/${a.slug}/v${v.version}/paper.pdf`, publicationId: a.links?.publicationId || null,
    projectIds: a.links?.projectIds || [], newsPostIds: a.links?.newsPostIds || [], venue: a.venue || null,
    versions: a.versions.map(x => ({ version: x.version, date: x.date, note: x.note || '', url: `preprints/${a.slug}/v${x.version}/`, pdf: `preprints/${a.slug}/v${x.version}/paper.pdf` })) };
}).sort((x, y) => y.date.localeCompare(x.date) || x.slug.localeCompare(y.slug));
outputs.set('assets/preprints-data.js', `// GENERATED by tools/build-preprints.mjs from preprints/<slug>/preprint.json. Do not edit by hand.\nwindow.PREPRINTS = ${JSON.stringify(data, null, 1)};\n`);

// Generated folders whose record disappeared (only folders this tool generated are touched).
const stale = [];
for (const slug of slugs) {
  if (articles.some(a => a.slug === slug)) continue;
  const idx = resolve(dir, slug, 'index.html');
  if (existsSync(idx) && (await readFile(idx, 'utf8')).includes(MARK) && !existsSync(resolve(dir, slug, 'preprint.json'))) stale.push(slug);
}
if (problems.length) { console.error(`Preprints invalid:\n- ${problems.join('\n- ')}`); process.exit(1); }

const changed = [];
for (const [rel, content] of outputs) {
  const t = resolve(root, rel);
  if (!existsSync(t) || (await readFile(t, 'utf8')) !== content) changed.push(rel);
}
for (const [rel, src] of binaries) {
  const t = resolve(root, rel);
  if (!existsSync(t) || sha(await readFile(t)) !== sha(await readFile(resolve(root, src)))) changed.push(rel);
}
if (check) {
  if (changed.length || stale.length) { console.error(`Preprints out of date (${[...changed, ...stale.map(s => `preprints/${s}/ (stale)`)].join(', ')}). Run: node tools/build-preprints.mjs`); process.exit(1); }
  console.log(`Preprints up to date: ${articles.length} article(s), ${articles.reduce((n, a) => n + a.versions.length, 0)} version(s).`);
} else {
  for (const rel of changed) {
    const t = resolve(root, rel);
    await mkdir(dirname(t), { recursive: true });
    await writeFile(t, binaries.has(rel) ? await readFile(resolve(root, binaries.get(rel))) : outputs.get(rel));
  }
  for (const s of stale) await rm(resolve(dir, s), { recursive: true });
  console.log(`Preprints built: ${articles.length} article(s); ${changed.length} file(s) written${stale.length ? `, removed ${stale.join(', ')}` : ''}.`);
}
