// Builds project pages: GitHub-style release history + Pinterest-style memory gallery.
//   Editable source:  projects/<slug>/project.json   (releases, gallery, team, extra links; optional "meta" for local-only projects)
//                     projects/<slug>/README.md      (optional overview, Markdown)
//   Read-only input:  assets/research-data.js        (generated from the CV via the lab site; names, statuses, publications)
//   Generates:        assets/projects-data.js, projects/<slug>/index.html
// New research projects that appear in research-data.js get a scaffolded project.json seeded from their
// publications and repository. Run: node tools/build-projects.mjs [--check]
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { renderMarkdown } from './news-markdown.mjs';
import { headOpen, headAssets, header, footer, maskWords } from './chrome.mjs';

const SITE = 'https://majidbabaei.com';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const MARK = '<!-- generated by tools/build-projects.mjs; edit projects/<slug>/project.json or README.md instead -->';
const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const slugify = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const projectSlug = name => slugify(name.split(' / ')[0]);
const STAGES = ['Idea', 'Prototype', 'Submitted', 'Accepted', 'Published'];

const ctx = { window: {} };
vm.runInNewContext(await readFile(resolve(root, 'assets/research-data.js'), 'utf8'), ctx);
const R = ctx.window.RESEARCH;

// Publications belong to a project when they share its repository or start with its short name.
const linkedPubs = p => {
  const short = p.name.split(' / ')[0].toLowerCase();
  const match = x => (x.code && x.code === p.url) || x.title.toLowerCase().startsWith(`${short}:`) || x.title.toLowerCase().startsWith(short + ' ');
  return [...R.published.filter(match).map(x => ({ ...x, kind: 'published' })), ...R.submitted.filter(match).map(x => ({ ...x, kind: 'submitted' }))];
};
const stageOf = (status, pubs, hasRepo) => {
  const s = `${status} ${pubs.map(p => `${p.status || ''} ${p.authors}`).join(' ')}`;
  if (pubs.some(p => p.kind === 'published' && !/to appear/i.test(p.authors))) return 'Published';
  if (/accepted|to appear/i.test(s)) return 'Accepted';
  if (/submitted|revision/i.test(s)) return 'Submitted';
  return hasRepo ? 'Prototype' : 'Idea';
};

// One-time seed data for scaffolding (dates recorded in the CV changelog / GitHub repository creation dates).
const REPO_CREATED = { skillspec: '2026-03-23', agentm2m: '2026-09-26', 'use-hpc': '2026-10-19', taaf: '2026-01-12', sikg: '2025-05-19', rapidpay: '2025-05-04',
  raten: '2025-11-14', mregtest: '2021-07-16', mreplayer: '2019-06-19', 'safe-coordination-of-untrusted-ai-agents': '2026-10-26', 'morph-fl': '2026-10-19',
  tint: '2026-10-29', 'agent-slicing': '2026-11-04', autom2m: '2026-10-08', 'res-ai': '2026-10-23', heartness: '2026-11-06' };
const STATUS_DATE = { skillspec: '2026-10', rapidpay: '2026-10-31', agentm2m: '2026-10', 'use-hpc': '2026-10-27', 'safe-coordination-of-untrusted-ai-agents': '2026-10-27',
  'morph-fl': '2026-10-29', tint: '2026-11-03', 'agent-slicing': '2026-11-06', autom2m: '2026-11-03', heartness: '2026-11-09', 'res-ai': '2026-10' };
function scaffold(slug, p, pubs) {
  const releases = [];
  for (const x of pubs) {
    const appear = /to appear/i.test(x.authors);
    const linkList = [x.paper && { label: 'Paper', url: x.paper, type: 'paper' }, x.preprint && { label: 'Preprint', url: x.preprint, type: 'paper' }].filter(Boolean);
    if (x.kind === 'published') releases.push({ tag: `${slugify(x.venue)}-${x.year}`, date: appear ? (STATUS_DATE[slug] || x.year) : x.year, type: 'paper',
      title: `${appear ? 'Accepted · ' : ''}${x.venue} ${x.year}${appear ? ' (to appear)' : ''}`, notes: `**${x.title}**\n\n${x.authors}`, links: linkList });
    else releases.push({ tag: x.status === 'On-going' ? 'v0-ongoing' : `${slugify(x.status)}-${slugify(x.venue)}`, date: STATUS_DATE[slug] || '2026',
      type: x.status === 'On-going' ? 'milestone' : 'paper', title: x.status === 'On-going' ? 'Research in progress' : `${x.status} · ${x.venue}`,
      notes: `**${x.title}**\n\n${x.authors}`, links: linkList });
  }
  if (REPO_CREATED[slug]) releases.push({ tag: 'code-public', date: REPO_CREATED[slug], type: 'code', title: 'Code repository published',
    notes: 'The research artifact is public on GitHub.', links: [{ label: 'Repository', url: p.url, type: 'code' }] });
  return { team: [], links: [], releases, gallery: [] };
}

const isoOf = d => { const [y, m, dd] = String(d).split('-'); return `${y}-${m || '01'}-${dd || '01'}`; };
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const labelOf = d => { const [y, m, dd] = String(d).split('-'); return dd ? `${MONTHS[m - 1]} ${Number(dd)}, ${y}` : m ? `${MONTHS[m - 1]} ${y}` : y; };
const authorsOf = pubs => [...new Set(pubs.flatMap(p => p.authors.split('.').length && p.authors.replace(/\. (pp\.|\d|ICSE|Research|Poster|To appear|LIFTDroid|MORPH-FL|AutoM2M|Heartness|ACM|Artifacts).*$/, '')
  .split(/,\s*(?:and\s+)?|\s+and\s+/).map(s => s.trim().replace(/\.$/, '')).filter(s => /^[A-Z]\./.test(s))))];

const ROOT = '../../';
const THEME_LABEL = { Agents: 'Agentic systems', Analysis: 'Analysis & testing', Infrastructure: 'Infrastructure', 'Student projects': 'Student projects' };
const THEME_COLOR = { Agents: 'var(--orange)', Analysis: 'var(--teal)', Infrastructure: 'var(--navy)', 'Student projects': 'var(--teal)' };
const STUDENT_STAGES = ['Proposal', 'Development', 'Poster', 'Completed'];
const ICON = {
  code: '<path d="m16 18 6-6-6-6M8 6l-6 6 6 6"/>',
  tag: '<path d="M3 3h8l10 10-8 8L3 11V3Z"/><circle cx="7.5" cy="7.5" r="1.5"/>',
  image: '<rect x="3" y="3" width="18" height="18" rx="2"/><circle cx="9" cy="9" r="2"/><path d="m21 15-5-5L5 21"/>',
  book: '<path d="M2 4h7a3 3 0 0 1 3 3v14a2 2 0 0 0-2-2H2V4Zm20 0h-7a3 3 0 0 0-3 3v14a2 2 0 0 1 2-2h8V4Z"/>'
};
const icon = n => `<svg class="ic" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICON[n]}</svg>`;
// The progress track is plain HTML so it reads without script; CSS fills it once on load.
const track = (stage, stages) => {
  const at = Math.max(0, stages.indexOf(stage));
  return `<ol class="track" style="--n:${stages.length};--at:${at}" aria-label="Progress: ${esc(stage)}">${stages.map((s, i) =>
    `<li class="${i < at ? 'done' : i === at ? 'now' : ''}"${i === at ? ' aria-current="step"' : ''}><span class="st-dot"></span><span class="st-l">${esc(s)}</span></li>`).join('')}</ol>`;
};

const page = proj => {
  const stages = proj.stages || (proj.research ? STAGES : STUDENT_STAGES);
  const cover = proj.gallery[0];
  return `<!doctype html>
${MARK}
<html lang="en">
<head>
${headOpen}
<title>${esc(proj.name)} · Projects | Majid Babaei</title>
<meta name="description" content="${esc(proj.description)}">
<link rel="canonical" href="${SITE}/projects/${proj.slug}/">
<meta property="og:type" content="website">
<meta property="og:title" content="${esc(proj.name)}: ${esc(proj.status)}">
<meta property="og:description" content="${esc(proj.description)}">
<meta property="og:image" content="${SITE}/${esc((cover && cover.src) || 'assets/img/portrait.jpg')}">
${headAssets(ROOT, ['news', 'projects'])}
</head>
<body class="reader" data-page="project" data-root="../../">
<a class="skip" href="#pj-content">Skip to content</a>
${header(ROOT, 'projects/')}
<main id="pj-main" style="--c:${THEME_COLOR[proj.theme] || 'var(--navy)'}">
  <header class="pj-hero wrap">
    <div class="pj-hero-text">
      <nav class="crumbs enter" aria-label="Breadcrumb"><a href="../">Projects</a><span aria-hidden="true">/</span><strong>${esc(THEME_LABEL[proj.theme] || proj.theme)}</strong></nav>
      <h1>${maskWords(proj.name, esc)}</h1>
      <p class="pj-lede enter" style="--i:1">${esc(proj.description)}</p>
      <div class="pj-actions enter" style="--i:2">
        ${proj.url ? `<a class="pj-btn" href="${esc(proj.url)}" target="_blank" rel="noopener">${icon('code')}View the code ↗</a>` : ''}
        <a class="pj-btn ghost" href="#releases">${icon('tag')}Release history</a>
        ${proj.gallery.length ? `<a class="pj-btn ghost" href="#gallery">${icon('image')}Gallery</a>` : ''}
      </div>
    </div>
    <figure class="pj-emblem" data-morph-target data-emblem="${proj.slug}" data-theme="${esc(proj.theme)}">${cover ? `<img class="settle" src="${ROOT}${esc(encodeURI(cover.src))}" alt="${esc(cover.alt || cover.caption || '')}" fetchpriority="high">` : ''}</figure>
  </header>
  <section class="pj-progress wrap" aria-label="Progress">
    <div class="pj-progress-h"><span>Progress</span><span>${esc(proj.status)}</span></div>
    ${track(proj.stage, stages)}
  </section>
  <div class="pj-bar">
    <nav class="wrap pj-tabs" id="pj-tabs" aria-label="Project sections">
      <a href="#overview" data-tab="overview">${icon('book')}Overview</a>
      <a href="#releases" data-tab="releases">${icon('tag')}Releases<span class="cnt">${proj.releases.length}</span></a>
      <a href="#gallery" data-tab="gallery">${icon('image')}Gallery<span class="cnt">${proj.gallery.length}</span></a>
    </nav>
  </div>
  <div class="wrap pj-grid">
    <div class="pj-content" id="pj-content" data-key="pj-content"><noscript><p>Enable JavaScript to view releases and the gallery.</p></noscript></div>
    <aside class="pj-side" id="pj-side" aria-label="About this project"></aside>
  </div>
</main>
${footer(ROOT)}
<script type="application/json" id="project-data">${JSON.stringify(proj).replace(/</g, '\\u003c')}</script>
<script src="../../assets/projects.js"></script>
<script src="../../assets/cv-request.js"></script>
<i id="page-ready" hidden></i>
</body>
</html>
`;
};

// Collect research projects plus local-only projects (folders whose project.json has "meta").
const dir = resolve(root, 'projects');
if (!existsSync(dir)) await mkdir(dir);
const folders = (await readdir(dir, { withFileTypes: true })).filter(e => e.isDirectory()).map(e => e.name);
const entries = R.projects.map(p => ({ base: p, slug: projectSlug(p.name), research: true }));
for (const f of folders) if (!entries.some(e => e.slug === f) && existsSync(resolve(dir, f, 'project.json'))) {
  const j = JSON.parse(await readFile(resolve(dir, f, 'project.json'), 'utf8'));
  if (j.meta) entries.push({ base: { url: '', tags: '', ...j.meta }, slug: f, research: false });
}

const outputs = new Map(), scaffolds = [];
const projects = [];
for (const { base, slug, research } of entries) {
  const pubs = research ? linkedPubs(base) : [];
  const jsonPath = resolve(dir, slug, 'project.json');
  let data;
  if (existsSync(jsonPath)) data = JSON.parse(await readFile(jsonPath, 'utf8'));
  else { data = scaffold(slug, base, pubs); scaffolds.push(`projects/${slug}/project.json`); outputs.set(`projects/${slug}/project.json`, JSON.stringify(data, null, 2) + '\n'); }
  const readmePath = resolve(dir, slug, 'README.md');
  const readme = existsSync(readmePath) ? await readFile(readmePath, 'utf8') : '';
  // Release notes and the README are rendered and sanitized here, so pages need no Markdown library at run time.
  const releases = (data.releases || []).map((r, i) => ({ ...r, notesHtml: r.notes ? renderMarkdown(r.notes) : '', iso: isoOf(r.date), label: r.label || labelOf(r.date), order: i }))
    .sort((a, b) => b.iso.localeCompare(a.iso) || a.order - b.order);
  const gallery = (data.gallery || []).map(g => ({ ...g, label: g.date ? (g.label || labelOf(g.date)) : (g.label || '') }));
  const proj = {
    slug, name: base.name, theme: base.theme, description: base.description, status: base.status, url: base.url || '', tags: base.tags || '',
    research, stage: data.stage || stageOf(base.status, pubs, Boolean(base.url)), stages: data.stages || null, team: data.team?.length ? data.team : authorsOf(pubs),
    links: data.links || [], publications: pubs.map(({ bibtex, ...x }) => ({ ...x, bibtex })), releases, gallery, readme, readmeHtml: readme ? renderMarkdown(readme) : '',
    updated: releases[0] ? releases[0].label : ''
  };
  projects.push(proj);
  outputs.set(`projects/${slug}/index.html`, page(proj).replace(/[\t ]+$/gm, ''));
}

const index = projects.map(({ publications, readme, readmeHtml, releases, gallery, ...p }) => ({
  ...p, releaseCount: releases.length, latest: releases[0] ? { tag: releases[0].tag, title: releases[0].title, label: releases[0].label, iso: releases[0].iso } : null,
  galleryCount: gallery.length, cover: gallery[0] ? gallery[0].src : null, types: [...new Set(releases.map(r => r.type))]
}));
const memories = projects.flatMap(p => p.gallery.map(g => ({ ...g, project: p.slug, projectName: p.name })))
  .sort((a, b) => isoOf(b.date || '0000').localeCompare(isoOf(a.date || '0000')));
outputs.set('assets/projects-data.js', `// GENERATED by tools/build-projects.mjs. Do not edit by hand.\nwindow.PROJECTS = ${JSON.stringify(index, null, 1)};\nwindow.MEMORIES = ${JSON.stringify(memories, null, 1)};\n`);

const changed = [];
for (const [rel, content] of outputs) {
  const t = resolve(root, rel);
  if (!existsSync(t) || (await readFile(t, 'utf8')) !== content) changed.push(rel);
}
if (check) {
  if (changed.length) { console.error(`Projects out of date (${changed.join(', ')}). Run: node tools/build-projects.mjs`); process.exit(1); }
  console.log(`Projects up to date: ${projects.length} projects, ${projects.reduce((n, p) => n + p.releases.length, 0)} releases, ${memories.length} memories.`);
} else {
  for (const rel of changed) { const t = resolve(root, rel); await mkdir(dirname(t), { recursive: true }); await writeFile(t, outputs.get(rel)); }
  console.log(`Projects built: ${projects.length} projects; ${changed.length} file(s) written${scaffolds.length ? `; scaffolded ${scaffolds.length} project.json` : ''}.`);
}
