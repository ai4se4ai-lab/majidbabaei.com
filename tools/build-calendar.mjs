/* ---------- Front matter ---------- */
function parse(file, text) {
  const m = text.replace(/^\uFEFF/, '').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].replace(/\s+#.*$/, '').trim();
    if (/^\[.*\]$/.test(v)) v = v.slice(1, -1).split(',').map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
    else if (v === 'true' || v === 'false') v = v === 'true';
    else v = v.replace(/^["']|["']$/g, '');
    meta[kv[1]] = v;
  }
  const err = msg => { throw new Error(`${file}: ${msg}`); };
  for (const k of ['title', 'type', 'start']) if (!meta[k]) err(`front matter needs "${k}"`);
  if (!TYPES[meta.type]) err(`unknown type "${meta.type}" (use ${Object.keys(TYPES).join(', ')})`);
  const start = C.parse(meta.start); if (!start) err(`start must be YYYY-MM-DD or YYYY-MM-DDTHH:MM, got "${meta.start}"`);
  const allDay = C.isAllDay(meta.start);
  let end = null;
  if (meta.end) {
    end = C.parse(meta.end); if (!end) err(`end must be YYYY-MM-DD or YYYY-MM-DDTHH:MM, got "${meta.end}"`);
    if (C.isAllDay(meta.end) !== allDay) err('start and end must both be dates or both be date-times');
    if (end < start) err('end is before start');
  }
  if (meta.repeat && meta.repeat !== 'weekly') err(`repeat must be "weekly" (got "${meta.repeat}")`);
  if (meta.repeat && !meta.until) err('a repeating entry needs "until"');
  if (meta.until && (!C.parse(meta.until) || !C.isAllDay(meta.until))) err('until must be YYYY-MM-DD');
  if (meta.until && C.parse(meta.until) < start) err('until is before start');
  const days = meta.days ? (Array.isArray(meta.days) ? meta.days : [meta.days]) : [];
  for (const d of days) if (!C.DAYS.includes(d)) err(`days must use ${C.DAYS.join(', ')}; got "${d}"`);
  const except = meta.except ? (Array.isArray(meta.except) ? meta.except : [meta.except]) : [];
  for (const d of except) if (!C.parse(d) || !C.isAllDay(d)) err(`except dates must be YYYY-MM-DD; got "${d}"`);
  if (meta.status && !['confirmed', 'tentative'].includes(meta.status)) err('status must be confirmed or tentative');
  if (meta.project && !existsSync(resolve(root, 'projects', meta.project, 'index.html'))) err(`project "${meta.project}" has no page under projects/`);
  const slug = file.replace(/\.md$/, '').replace(/^\d{4}(-\d{2}){0,2}-/, '');
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) err(`slug "${slug}" must be lowercase letters, digits and hyphens`);
  const body = m[2].trim();
  return {
    slug, title: meta.title, type: meta.type, start: meta.start, end: meta.end || null, allDay,
    repeat: meta.repeat || null, days: meta.repeat ? (days.length ? days : [C.DAYS[C.dow(start)]]) : [], interval: meta.repeat ? Math.max(1, Number(meta.interval) || 1) : 1,
    until: meta.repeat ? meta.until : null, except: meta.repeat ? except : [],
    location: meta.location || '', link: meta.link || '', project: meta.project || '',
    tags: Array.isArray(meta.tags) ? meta.tags : meta.tags ? [meta.tags] : [], summary: meta.summary || '', status: meta.status || 'confirmed',
    hasBody: body.length > 0, body, startDate: start
  };
}

