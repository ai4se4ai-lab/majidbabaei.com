// Builds project pages: GitHub-style release history + Pinterest-style memory gallery.
//   Editable source:  projects/<slug>/project.json   (releases, gallery, team, extra links; optional "meta" for local-only projects)
//                     projects/<slug>/README.md      (optional overview, Markdown)
//   Read-only input:  assets/research-data.js        (generated from the CV via the lab site; names, statuses, publications)
//   Generates:        assets/projects-data.js, projects/<slug>/index.html
// New research projects that appear in research-data.js get a scaffolded project.json seeded from their
// publications and repository. Run: node tools/build-projects.mjs [--check]
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const SITE = 'https://majidbabaei.com';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const MARK = '<!-- generated by tools/build-projects.mjs; edit projects/<slug>/project.json or README.md instead -->';
const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const slugify = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const projectSlug = name => slugify(name.split(' / ')[0]);
const STAGES = ['Idea', 'Prototype', 'Submitted', 'Accepted', 'Published'];

const ctx = { window: {} };
vm.runInNewContext(await readFile(resolve(root, 'assets/research-data.js'), 'utf8'), ctx);
const R = ctx.window.RESEARCH;

// Publications belong to a project when they share its repository or start with its short name.
const linkedPubs = p => {
  const short = p.name.split(' / ')[0].toLowerCase();
  const match = x => (x.code && x.code === p.url) || x.title.toLowerCase().startsWith(`${short}:`) || x.title.toLowerCase().startsWith(short + ' ');
  return [...R.published.filter(match).map(x => ({ ...x, kind: 'published' })), ...R.submitted.filter(match).map(x => ({ ...x, kind: 'submitted' }))];
};
const stageOf = (status, pubs, hasRepo) => {
  const s = `${status} ${pubs.map(p => `${p.status || ''} ${p.authors}`).join(' ')}`;
  if (pubs.some(p => p.kind === 'published' && !/to appear/i.test(p.authors))) return 'Published';
  if (/accepted|to appear/i.test(s)) return 'Accepted';
  if (/submitted|revision/i.test(s)) return 'Submitted';
  return hasRepo ? 'Prototype' : 'Idea';
};

// One-time seed data for scaffolding (dates recorded in the CV changelog / GitHub repository creation dates).
const REPO_CREATED = { skillspec: '2026-03-23', agentm2m: '2026-09-26', 'use-hpc': '2026-10-19', taaf: '2026-01-12', sikg: '2025-05-19', rapidpay: '2025-05-04',
  raten: '2025-11-14', mregtest: '2021-07-16', mreplayer: '2019-06-19', 'safe-coordination-of-untrusted-ai-agents': '2026-10-26', 'morph-fl': '2026-10-19',
  tint: '2026-10-29', 'agent-slicing': '2026-11-04', autom2m: '2026-10-08', 'res-ai': '2026-10-23', heartness: '2026-11-06' };
const STATUS_DATE = { skillspec: '2026-10', rapidpay: '2026-10-31', agentm2m: '2026-10', 'use-hpc': '2026-10-27', 'safe-coordination-of-untrusted-ai-agents': '2026-10-27',
  'morph-fl': '2026-10-29', tint: '2026-11-03', 'agent-slicing': '2026-11-06', autom2m: '2026-11-03', heartness: '2026-11-09', 'res-ai': '2026-10' };
function scaffold(slug, p, pubs) {
  const releases = [];
  for (const x of pubs) {
    const appear = /to appear/i.test(x.authors);
    const linkList = [x.paper && { label: 'Paper', url: x.paper, type: 'paper' }, x.preprint && { label: 'Preprint', url: x.preprint, type: 'paper' }].filter(Boolean);
    if (x.kind === 'published') releases.push({ tag: `${slugify(x.venue)}-${x.year}`, date: appear ? (STATUS_DATE[slug] || x.year) : x.year, type: 'paper',
      title: `${appear ? 'Accepted · ' : ''}${x.venue} ${x.year}${appear ? ' (to appear)' : ''}`, notes: `**${x.title}**\n\n${x.authors}`, links: linkList });
    else releases.push({ tag: x.status === 'On-going' ? 'v0-ongoing' : `${slugify(x.status)}-${slugify(x.venue)}`, date: STATUS_DATE[slug] || '2026',
      type: x.status === 'On-going' ? 'milestone' : 'paper', title: x.status === 'On-going' ? 'Research in progress' : `${x.status} · ${x.venue}`,
      notes: `**${x.title}**\n\n${x.authors}`, links: linkList });
  }
  if (REPO_CREATED[slug]) releases.push({ tag: 'code-public', date: REPO_CREATED[slug], type: 'code', title: 'Code repository published',
    notes: 'The research artifact is public on GitHub.', links: [{ label: 'Repository', url: p.url, type: 'code' }] });
  return { team: [], links: [], releases, gallery: [] };
}

const isoOf = d => { const [y, m, dd] = String(d).split('-'); return `${y}-${m || '01'}-${dd || '01'}`; };
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const labelOf = d => { const [y, m, dd] = String(d).split('-'); return dd ? `${MONTHS[m - 1]} ${Number(dd)}, ${y}` : m ? `${MONTHS[m - 1]} ${y}` : y; };
const authorsOf = pubs => [...new Set(pubs.flatMap(p => p.authors.split('.').length && p.authors.replace(/\. (pp\.|\d|ICSE|Research|Poster|To appear|LIFTDroid|MORPH-FL|AutoM2M|Heartness|ACM|Artifacts).*$/, '')
  .split(/,\s*(?:and\s+)?|\s+and\s+/).map(s => s.trim().replace(/\.$/, '')).filter(s => /^[A-Z]\./.test(s))))];

