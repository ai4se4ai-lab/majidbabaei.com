const xml = v => esc(v);
const rss = posts => `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
<title>Majid Babaei: News &amp; Notes</title>
<link>${SITE}/news/</link>
<atom:link href="${SITE}/news/feed.xml" rel="self" type="application/rss+xml"/>
<description>Research progress, publications, teaching, and students from Majid Babaei's group.</description>
<language>en</language>
${posts.map(p => `<item><title>${xml(p.title)}</title><link>${SITE}/news/${p.slug}/</link><guid>${SITE}/news/${p.slug}/</guid><pubDate>${new Date(`${p.iso}T12:00:00Z`).toUTCString()}</pubDate>${p.tags.map(t => `<category>${xml(t)}</category>`).join('')}<description>${xml(p.summary)}</description></item>`).join('\n')}
</channel>
</rss>
`;
const sitemap = posts => `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
<url><loc>${SITE}/</loc></url>
<url><loc>${SITE}/news/</loc></url>
${posts.map(p => `<url><loc>${SITE}/news/${p.slug}/</loc><lastmod>${p.iso}</lastmod></url>`).join('\n')}
</urlset>
`;

const postsDir = resolve(root, 'news/posts');
const files = (await readdir(postsDir)).filter(f => f.endsWith('.md')).sort();
const posts = [];
for (const file of files) posts.push({ ...parse(file, await readFile(resolve(postsDir, file), 'utf8')), file });
const dupes = posts.map(p => p.slug).filter((s, i, a) => a.indexOf(s) !== i);
if (dupes.length) throw new Error(`Duplicate news slugs: ${dupes.join(', ')}`);
posts.sort((a, b) => b.iso.localeCompare(a.iso) || b.date.length - a.date.length || a.slug.localeCompare(b.slug));

// Social crawlers read the initial HTML and need an absolute raster image URL.
for (const p of posts) {
  const image = p.socialImage || p.cover || '/assets/img/portrait.jpg';
  p.imageURL = new URL(image, SITE).href;
  if (new URL(p.imageURL).origin === SITE) {
    const pathname = decodeURIComponent(new URL(p.imageURL).pathname);
    const path = resolve(root, '.' + pathname);
    if (!path.startsWith(root + '/') && !path.startsWith(root + '\\')) throw new Error(`Invalid image path: ${image}`);
    if (!existsSync(path)) throw new Error(`${p.file}: image does not exist: ${image}`);
    if (/\.svg$/i.test(pathname)) throw new Error(`${p.file}: set socialImage to a PNG or JPEG export of the top figure`);
    const data = await readFile(path);
    if (data.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
      p.imageSize = { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
    }
  }
}
const meta = posts.map(({ body, file, imageSize, ...p }) => p);
const outputs = new Map([
  ['assets/news-data.js', `// GENERATED by tools/build-news.mjs from news/posts/*.md. Do not edit by hand.\nwindow.NEWS = ${JSON.stringify(meta, null, 1)};\n`],
  ['news/feed.xml', rss(posts)],
  ['sitemap.xml', sitemap(posts)],
  ...posts.map(p => [`news/${p.slug}/index.html`, page(p)])
]);

// Generated article folders that no longer have a source post.
const slugs = new Set(posts.map(p => p.slug));
const stale = [];
for (const entry of await readdir(resolve(root, 'news'), { withFileTypes: true })) {
  const idx = resolve(root, 'news', entry.name, 'index.html');
  if (entry.isDirectory() && !slugs.has(entry.name) && existsSync(idx) && (await readFile(idx, 'utf8')).includes(MARK)) stale.push(entry.name);
}

const changed = [];
for (const [rel, content] of outputs) {
  const target = resolve(root, rel);
  const current = existsSync(target) ? await readFile(target, 'utf8') : null;
  if (current !== content) changed.push(rel);
}
if (check) {
  if (changed.length || stale.length) {
    console.error(`Newsroom out of date (${[...changed, ...stale.map(s => `news/${s}/ (stale)`)].join(', ')}). Run: node tools/build-news.mjs`);
    process.exit(1);
  }
  console.log(`Newsroom up to date: ${posts.length} posts.`);
} else {
  for (const rel of changed) { const t = resolve(root, rel); await mkdir(dirname(t), { recursive: true }); await writeFile(t, outputs.get(rel)); }
  for (const s of stale) await rm(resolve(root, 'news', s), { recursive: true });
  console.log(`Newsroom built: ${posts.length} posts; ${changed.length} file(s) written${stale.length ? `, removed ${stale.join(', ')}` : ''}.`);
}
