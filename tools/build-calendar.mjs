//              calendar/<slug>/index.html         (one detail page per entry; Markdown rendered at build time)
//              calendar/<slug>/event.ics, calendar/feed.ics   (iCalendar, with RRULE/EXDATE for repeating entries)
// Usage: node tools/build-calendar.mjs [--check]   (run from anywhere)
