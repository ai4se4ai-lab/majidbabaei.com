/* ---------- iCalendar ---------- */
const icsText = v => String(v ?? '').replace(/\\/g, '\\\\').replace(/;/g, '\\;').replace(/,/g, '\\,').replace(/\r?\n/g, '\\n');
const icsDate = s => s.replace(/-/g, '').replace(':', '') + (s.includes('T') ? '00' : '');
const fold = line => { const out = []; let s = line; while (Buffer.byteLength(s) > 73) { let cut = 73; while (Buffer.byteLength(s.slice(0, cut)) > 73) cut--; out.push(s.slice(0, cut)); s = ' ' + s.slice(cut); } out.push(s); return out.join('\r\n'); };
const BYDAY = { Mon: 'MO', Tue: 'TU', Wed: 'WE', Thu: 'TH', Fri: 'FR', Sat: 'SA', Sun: 'SU' };
export function vevent(e, stamp) {
  const lines = [`BEGIN:VEVENT`, `UID:${e.slug}@majidbabaei.com`, `DTSTAMP:${stamp}`, `SUMMARY:${icsText(e.title)}`];
  if (e.allDay) {
    const endEx = C.key(C.addDays(C.parse(e.end || e.start), 1));
    lines.push(`DTSTART;VALUE=DATE:${icsDate(e.start)}`, `DTEND;VALUE=DATE:${icsDate(endEx)}`);
  } else {
    const end = e.end || C.key(C.parse(e.start)) + 'T' + C.time24(new Date(C.parse(e.start).getTime() + 3600000));
    lines.push(`DTSTART;TZID=${TIMEZONE}:${icsDate(e.start)}`, `DTEND;TZID=${TIMEZONE}:${icsDate(end)}`);
  }
  if (e.repeat) {
    lines.push(`RRULE:FREQ=WEEKLY;INTERVAL=${e.interval};BYDAY=${e.days.map(d => BYDAY[d]).join(',')};UNTIL=${icsDate(e.until)}${e.allDay ? '' : 'T235959'}`);
    for (const x of e.except) lines.push(e.allDay ? `EXDATE;VALUE=DATE:${icsDate(x)}` : `EXDATE;TZID=${TIMEZONE}:${icsDate(x)}T${e.start.slice(11).replace(':', '')}00`);
  }
  const desc = [e.summary, e.link].filter(Boolean).join('\n');
  if (desc) lines.push(`DESCRIPTION:${icsText(desc)}`);
  if (e.location) lines.push(`LOCATION:${icsText(e.location)}`);
  lines.push(`URL:${SITE}/calendar/${e.slug}/`, `CATEGORIES:${icsText(TYPES[e.type].label)}`, `STATUS:${e.status === 'tentative' ? 'TENTATIVE' : 'CONFIRMED'}`, 'END:VEVENT');
  return lines.map(fold).join('\r\n');
}
const vcalendar = (events, stamp) => ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//majidbabaei.com//calendar//EN', 'CALSCALE:GREGORIAN', 'METHOD:PUBLISH',
  fold(`X-WR-CALNAME:${icsText('Majid Babaei: commitments')}`), `X-WR-TIMEZONE:${TIMEZONE}`, ...events.map(e => vevent(e, stamp)), 'END:VCALENDAR'].join('\r\n') + '\r\n';

/* ---------- Build ---------- */
const dir = resolve(root, 'calendar/events');
if (!existsSync(dir)) await mkdir(dir, { recursive: true });
const files = (await readdir(dir)).filter(f => f.endsWith('.md') && !f.startsWith('_')).sort();
const events = [];
for (const file of files) events.push({ ...parse(file, await readFile(resolve(dir, file), 'utf8')), file });
const dupes = events.map(e => e.slug).filter((s, i, a) => a.indexOf(s) !== i);
if (dupes.length) throw new Error(`Duplicate calendar slugs: ${dupes.join(', ')}`);
events.sort((a, b) => a.startDate - b.startDate || a.slug.localeCompare(b.slug));

// Project names for the detail rail (generated from the CV via build-projects.mjs).
const pctx = { window: {} };
if (existsSync(resolve(root, 'assets/projects-data.js'))) vm.runInNewContext(await readFile(resolve(root, 'assets/projects-data.js'), 'utf8'), pctx);
const projectName = slug => (pctx.window.PROJECTS || []).find(p => p.slug === slug)?.name || '';

for (const e of events) {
  const one = C.expand([e], new Date(1970, 0, 1), new Date(2100, 0, 1))[0];
  e.whenLabel = one ? C.when(one) : e.start;
  if (e.project) e.projectName = projectName(e.project);
}
// A stable stamp: the newest source file decides, so unchanged inputs produce unchanged outputs.
const stamp = '20260101T000000Z';
const data = { timezone: TIMEZONE, types: Object.fromEntries(Object.entries(TYPES).map(([k, v]) => [k, v.label])),
  events: events.map(({ body, file, startDate, hasBody, ...e }) => ({ ...e, hasPage: true, url: `calendar/${e.slug}/` })) };
const outputs = new Map([
  ['assets/calendar-data.js', `// GENERATED by tools/build-calendar.mjs from calendar/events/*.md. Do not edit by hand.\nwindow.CALENDAR = ${JSON.stringify(data, null, 1)};\n`],
  ['calendar/feed.ics', vcalendar(events, stamp)],
  ...events.map((e, i) => [`calendar/${e.slug}/index.html`, page(e, events[i - 1], events[i + 1])]),
  ...events.map(e => [`calendar/${e.slug}/event.ics`, vcalendar([e], stamp)])
]);

// Generated entry folders that no longer have a source file.
const slugs = new Set(events.map(e => e.slug));
const stale = [];
for (const entry of await readdir(resolve(root, 'calendar'), { withFileTypes: true })) {
  const idx = resolve(root, 'calendar', entry.name, 'index.html');
  if (entry.isDirectory() && !slugs.has(entry.name) && existsSync(idx) && (await readFile(idx, 'utf8')).includes(MARK)) stale.push(entry.name);
}

const changed = [];
for (const [rel, content] of outputs) {
  const target = resolve(root, rel);
  const current = existsSync(target) ? await readFile(target, 'utf8') : null;
  if (current !== content) changed.push(rel);
}
if (check) {
  if (changed.length || stale.length) {
    console.error(`Calendar out of date (${[...changed, ...stale.map(s => `calendar/${s}/ (stale)`)].join(', ')}). Run: node tools/build-calendar.mjs`);
    process.exit(1);
  }
  console.log(`Calendar up to date: ${events.length} entries.`);
} else {
  for (const rel of changed) { const t = resolve(root, rel); await mkdir(dirname(t), { recursive: true }); await writeFile(t, outputs.get(rel)); }
  for (const s of stale) await rm(resolve(root, 'calendar', s), { recursive: true });
  console.log(`Calendar built: ${events.length} entries; ${changed.length} file(s) written${stale.length ? `, removed ${stale.join(', ')}` : ''}.`);
}
